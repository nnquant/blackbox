const dictionaries = {
  'zh-CN': zhCN,
  'en-US': {},
};

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale) {
  currentLocale = supportedLocales.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function t(key, replacements) {
  const raw = key === undefined || key === null ? '' : String(key);
  const translated = dictionaries[currentLocale]?.[raw] ?? raw;
  if (!replacements) return translated;
  return translated.replace(/\{\{(\w+)\}\}/g, (_, name) => (
    replacements[name] === undefined || replacements[name] === null ? '' : String(replacements[name])
  ));
}

export function tx(value) {
  return typeof value === 'string' ? t(value) : value;
}

export function tStatus(status) {
  return status ? t(String(status)) : '--';
}
